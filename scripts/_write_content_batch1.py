TPL = '''import type {{ ToolContent }} from "@/lib/tool-content";

const content: ToolContent = {{
  intro:
    {intro!r},
  steps: [
{steps}  ],
  useCases: [
{uses}  ],
  faqs: [
{faqs}  ],
}};

export default content;
'''


def jsstr(s):
    # 用 JSON 风格双引号，避免 Python repr 的单引号在 TS 里不统一
    import json
    return json.dumps(s, ensure_ascii=False)


def cjk_count(c):
    joined = c["intro"] + "".join(x["title"] + x["body"] for x in c["steps"]) + "".join(c["useCases"]) + "".join(x["q"] + x["a"] for x in c["faqs"])
    return len(re.findall(r"[\u4e00-\u9fff]", joined))


def trim_to_range(c, lo=600, hi=800):
    """压缩到 800 字内：先减场景/FAQ 条数，再精简 intro 与步骤描述。保持语义完整。"""
    # 场景最多 5 条，FAQ 保持 4–5 条
    if len(c["useCases"]) > 5:
        c["useCases"] = c["useCases"][:5]
    if cjk_count(c) <= hi:
        return c
    if len(c["faqs"]) > 4:
        c["faqs"] = c["faqs"][:4]
    if cjk_count(c) <= hi:
        return c
    # intro 保留前 4 句（保证简介+优势完整）
    parts = re.split(r"(?<=。)", c["intro"])
    while len(parts) > 3 and cjk_count(c) > hi:
        parts.pop()
        c["intro"] = "".join(parts)
    if cjk_count(c) <= hi:
        return c
    # 步骤描述：从最后一步开始逐步精简到前 2 句，直到达标
    for s in reversed(c["steps"]):
        if cjk_count(c) <= hi:
            break
        ps = re.split(r"(?<=。)", s["body"])
        s["body"] = "".join(ps[:2])
    return c


def render(c):
    steps = "".join(
        f"    {{\n      title: {jsstr(x['title'])},\n      body: {jsstr(x['body'])},\n    }},\n"
        for x in c["steps"]
    )
    uses = "".join(f"    {jsstr(x)},\n" for x in c["useCases"])
    faqs = "".join(
        f"    {{\n      q: {jsstr(x['q'])},\n      a: {jsstr(x['a'])},\n    }},\n"
        for x in c["faqs"]
    )
    return TPL.format(intro=jsstr(c["intro"]), steps=steps, uses=uses, faqs=faqs)


