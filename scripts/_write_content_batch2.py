TPL = '''import type {{ ToolContent }} from "@/lib/tool-content";

const content: ToolContent = {{
  intro:
    {intro},
  steps: [
{steps}  ],
  useCases: [
{uses}  ],
  faqs: [
{faqs}  ],
}};

export default content;
'''


def jsstr(s):
    return json.dumps(s, ensure_ascii=False)


def cjk_count(c):
    joined = c["intro"] + "".join(x["title"] + x["body"] for x in c["steps"]) + "".join(c["useCases"]) + "".join(x["q"] + x["a"] for x in c["faqs"])
    return len(re.findall(r"[\u4e00-\u9fff]", joined))


def trim(c, hi=800):
    if cjk_count(c) <= hi:
        return c
    if len(c["faqs"]) > 4:
        c["faqs"] = c["faqs"][:4]
    if cjk_count(c) <= hi:
        return c
    parts = re.split(r"(?<=。)", c["intro"])
    while len(parts) > 3 and cjk_count(c) > hi:
        parts.pop()
        c["intro"] = "".join(parts)
    for s in reversed(c["steps"]):
        if cjk_count(c) <= hi:
            break
        ps = re.split(r"(?<=。)", s["body"])
        s["body"] = "".join(ps[:2])
    return c


for slug, c in CONTENT.items():
    c = trim(c)
    path = os.path.join(BASE, slug, "content.ts")
    steps = "".join(f"    {{\n      title: {jsstr(x['title'])},\n      body: {jsstr(x['body'])},\n    }},\n" for x in c["steps"])
    uses = "".join(f"    {jsstr(x)},\n" for x in c["useCases"])
    faqs = "".join(f"    {{\n      q: {jsstr(x['q'])},\n      a: {jsstr(x['a'])},\n    }},\n" for x in c["faqs"])
    open(path, "w", encoding="utf-8", newline="").write(
        TPL.format(intro=jsstr(c["intro"]), steps=steps, uses=uses, faqs=faqs)
    )
    n = cjk_count(c)
    print(f"{'OK' if 600 <= n <= 800 else 'CHECK':5} {slug:24} CJK={n}")
